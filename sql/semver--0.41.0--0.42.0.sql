	AS 'MODULE_PATHNAME', 'bigint_to_semver'
	LANGUAGE C STRICT IMMUTABLE PARALLEL SAFE;

CREATE OR REPLACE FUNCTION hash_semver_extended(semver, int8)
	RETURNS int8
	AS 'MODULE_PATHNAME'
	LANGUAGE C STRICT IMMUTABLE PARALLEL SAFE;

ALTER OPERATOR FAMILY semver_ops USING hash
	ADD FUNCTION 2 (semver, semver) hash_semver_extended(semver, bigint);

